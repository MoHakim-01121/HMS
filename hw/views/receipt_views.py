"""Receipt views — void + PDF.

A receipt (kwitansi) is a payment document generated from a PaymentRecord.
The generated PDF serves as the printable money receipt. Receipts are
auto-generated by hw.finance.receipt_service.ensure_receipt when a payment
becomes effective (see payment confirm / record flows).

Per best practice (Stripe/Xero), receipts are surfaced only from the Payment
detail page (with a direct "View PDF" action); there is no standalone receipt
list/detail module.

The PDF is deliberately two zones. The upper zone prints what the Receipt row
itself stores -- amount, method, date, note -- which ensure_receipt copies off
the payment at issue time, so a reprint always shows the amount that was
actually receipted. The lower zone (the description table and the invoice
balance) prints live state, which legitimately changes after issue when
finance re-applies the money, so the balance line carries an "as at" date.
"""
import logging

from django.contrib import messages
from django.shortcuts import redirect
from django.utils import timezone

from ..branch_scope import get_in_scope_or_404
from ..i18n import tr
from ..models import Receipt
from ..permissions import require_perm
from .pdf import _stay_label

logger = logging.getLogger(__name__)


@require_perm('payments', 'delete')
def receipt_void(request, pk):
    receipt = get_in_scope_or_404(Receipt.objects.all(), request.user, pk=pk)
    if request.method == "POST":
        reason = request.POST.get("reason", "").strip()
        receipt.status = Receipt.STATUS_VOIDED
        receipt.voided_reason = reason
        receipt.save(update_fields=['status', 'voided_reason'])
        messages.success(request, tr(request, f"Receipt {receipt.receipt_number} voided.", f"Receipt {receipt.receipt_number} dibatalkan (voided)."))
        if receipt.payment_id:
            return redirect("payment_detail", pk=receipt.payment_id)
    return redirect("payment_list")


def _number_in_words(n):
    """Whole number to English words (e.g. 48750 -> 'forty-eight thousand...')."""
    ones = ['', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight',
            'nine', 'ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen',
            'sixteen', 'seventeen', 'eighteen', 'nineteen']
    tens = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy',
            'eighty', 'ninety']

    def two(num):
        if num == 0:
            return ''
        if num < 20:
            return ones[num]
        d, r = divmod(num, 10)
        return tens[d] + ('-' + ones[r] if r else '')

    def three(num):
        h, r = divmod(num, 100)
        parts = []
        if h:
            parts.append(ones[h] + ' hundred')
        if r:
            parts.append(two(r))
        return ' '.join(parts)

    if n == 0:
        return 'zero'
    scales = ['', ' thousand', ' million', ' billion']
    out, i = [], 0
    while n and i < len(scales):
        n, rem = divmod(n, 1000)
        if rem:
            out.append(three(rem) + scales[i])
        i += 1
    return ' '.join(reversed([c for c in out if c]))


_CURRENCY_NAMES = {'SAR': 'Saudi Riyal', 'IDR': 'Indonesian Rupiah', 'USD': 'US Dollar'}


def _amount_in_words(amount, currency):
    words = _number_in_words(amount).capitalize()
    return f"{words} {_CURRENCY_NAMES.get(currency, currency)}"


def _paid_how(method):
    """'by bank transfer'; the method 'Direct' reads 'directly'."""
    method = (method or 'cash').lower()
    return 'directly' if method == 'direct' else f"by {method}"


def _client_reference(reference):
    """The bank reference for print; 'legacy:<id>' is a marker from the data migration."""
    return None if (reference or '').startswith('legacy:') else reference


def _invoice_balance(invoice):
    """Live total/paid/balance of the paid invoice; None for a deposit or void invoice."""
    if invoice is None or invoice.is_void:
        return None
    balance = invoice.remaining_sar
    return {
        'due': f"{invoice.due_sar:,}",
        'paid': f"{invoice.applied_paid_sar:,}",
        'balance': f"{abs(balance):,}",
        'owing': balance > 0,
        'overpaid': balance < 0,
    }


def _allocation_rows(payment):
    """Rows for the 'Application of funds' block.

    Two allocation shapes exist, matching finance.queries.payment_unallocated_sar:
    explicit PaymentAllocation rows, or -- for a payment bound directly to a
    single reservation with no allocation rows -- that one target, treated as
    fully allocated.
    """
    if payment is None:
        return []

    rows = []
    for a in payment.allocations.select_related(
        'invoice_line__confirmation_letter__hotel', 'invoice_line__invoice',
    ).order_by('pk'):
        line = a.invoice_line
        # A reallocation can apply the payment to another invoice of the same
        # client; name that invoice so the receipt reads unambiguously.
        other_invoice = line.invoice.invoice_number if line.invoice_id != payment.invoice_id else ''
        if line.kind == line.KIND_HOTEL:
            parts = (line.reservation_number, line.hotel, other_invoice, _stay_label(line.check_in, line.check_out))
            label = line.reservation_number
        else:
            parts = (line.description, f'Service item x{line.quantity}', other_invoice)
            label = line.description
        rows.append({
            'label': label,
            'description': ', '.join(p for p in parts if p),
            'amount_sar': a.amount_sar,
        })

    for row in rows:
        row['amount_fmt'] = f"{row['amount_sar']:,}"
    return rows


@require_perm('payments', 'export')
def receipt_pdf(request, pk):
    receipt = get_in_scope_or_404(
        Receipt.objects.select_related(
            'client', 'invoice', 'payment', 'confirmation_letter',
        ),
        request.user, pk=pk,
    )
    from django.conf import settings
    from django.http import HttpResponse
    from django.template.loader import render_to_string
    from weasyprint import HTML

    from .pdf import _logo_file_url

    cl = receipt.confirmation_letter
    payment = receipt.payment
    currency = payment.currency if payment else None
    rate = float(payment.exchange_rate) if payment else None
    if currency == 'SAR':
        exchange_label = None
    elif currency == 'IDR':
        exchange_label = f"1 SAR = {rate:,.2f}".removesuffix('.00') + " IDR"
    elif currency is not None and rate is not None:
        exchange_label = f"1 {currency} = {rate:,.2f}".removesuffix('.00') + " SAR"
    else:
        exchange_label = None

    allocation_rows = _allocation_rows(payment)
    allocated_sar = sum(r['amount_sar'] for r in allocation_rows)
    # The printed column has to reconcile against the receipt's own total, so
    # the remainder is derived from the rows. fq.payment_unallocated_sar is the
    # same figure the payment detail page shows; the two can only diverge if a
    # receipt's amount stops matching its payment, which ensure_receipt (it
    # copies payment.amount_sar) prevents. Log it rather than print a document
    # whose numbers disagree with the app.
    unapplied_sar = max(receipt.amount_sar - allocated_sar, 0)
    if payment is not None:
        from ..finance import queries as fq
        helper_unapplied = fq.payment_unallocated_sar(payment.pk)
        if helper_unapplied != unapplied_sar:
            logger.warning(
                "receipt %s: unapplied mismatch (receipt-derived %s, helper %s)",
                receipt.receipt_number, unapplied_sar, helper_unapplied,
            )

    paid_amount = payment.amount if payment else receipt.amount_sar
    paid_currency = currency or 'SAR'

    context = {
        "logo_rel_path": _logo_file_url(),
        "receipt_number": receipt.receipt_number,
        "receipt_date": receipt.receipt_date,
        "payment_date": payment.payment_date if payment else None,
        "payment_number": payment.payment_number if payment else None,
        "invoice_number": receipt.invoice.invoice_number if receipt.invoice else None,
        "client_name": receipt.client.name if receipt.client else None,
        "confirmation_number": cl.confirmation_number if cl else None,
        "hotel_name": cl.hotel_name if cl else None,
        "guest_name": cl.guest_name if cl else None,
        "check_in": cl.check_in if cl else None,
        "check_out": cl.check_out if cl else None,
        "amount_sar_fmt": f"{receipt.amount_sar:,}",
        "paid_amount_fmt": f"{paid_amount:,}",
        "amount_sar_words": _amount_in_words(receipt.amount_sar, 'SAR'),
        "paid_currency": paid_currency,
        "exchange_label": exchange_label,
        "received_office": payment.get_received_in_display() if payment and payment.receiving_account_id else None,
        "invoice_balance": _invoice_balance(receipt.invoice),
        "payment_method": receipt.payment_method,
        "paid_how": _paid_how(receipt.payment_method),
        "bank_reference": _client_reference(payment.reference) if payment else None,
        "payment_note": receipt.payment_note,
        "status": receipt.status,
        "voided_reason": receipt.voided_reason,
        "received_by": receipt.created_by.get_full_name() or receipt.created_by.username,
        "allocation_rows": allocation_rows,
        "unapplied_sar_fmt": f"{unapplied_sar:,}" if unapplied_sar else None,
        "printed_at_ts": timezone.localtime(timezone.now()),
    }

    html = render_to_string("hw/receipt/receipt_pdf.html", context)
    pdf = HTML(string=html, base_url=str(settings.BASE_DIR)).write_pdf()
    filename = f"{receipt.receipt_number}.pdf"
    response = HttpResponse(pdf, content_type="application/pdf")
    response["Content-Disposition"] = f'inline; filename="{filename}"'
    return response
